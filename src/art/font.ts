export const FONT_CHARS = Object.keys(G).join('');

export function buildFont(scene: Phaser.Scene): void {
  const chars = FONT_CHARS;
  const tex = scene.textures.createCanvas(FONT_KEY + '_img', chars.length * FONT_CELL_W, FONT_CELL_H)!;
  const ctx = tex.getContext();
  for (let i = 0; i < chars.length; i++) {
    const glyph = G[chars[i]];
    const ox = i * FONT_CELL_W;
    // shadow first, then the glyph on top
    ctx.fillStyle = P.ink;
    glyph.forEach((row, y) => {
      for (let x = 0; x < 5; x++) if (row[x] === '#') ctx.fillRect(ox + x + 1, y + 1, 1, 1);
    });
    ctx.fillStyle = '#ffffff';
    glyph.forEach((row, y) => {
      for (let x = 0; x < 5; x++) if (row[x] === '#') ctx.fillRect(ox + x, y, 1, 1);
    });
  }
  tex.refresh();

  const data = Phaser.GameObjects.RetroFont.Parse(scene, {
    image: FONT_KEY + '_img',
    width: FONT_CELL_W,
    height: FONT_CELL_H,
    chars,
    charsPerRow: chars.length,
    'offset.x': 0,
    'offset.y': 0,
    'spacing.x': 0,
    'spacing.y': 0,
    lineSpacing: 3,
  });
  scene.cache.bitmapFont.add(FONT_KEY, data);
}
